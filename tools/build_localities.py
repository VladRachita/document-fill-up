"""Rebuild ``src/docfill/data/ro_localities.txt`` from the SIRUTA data of ``django-siruta``.

SIRUTA is the official register of the localities of Romania (Institutul Național de
Statistică). The ``django-siruta`` package (BSD 2-Clause) republishes its names per county, in
capitals and with the legacy cedilla letters; this script turns them into the spelling of the
identity card (capitalised words, comma-below ș / ț) and keeps one name per line, grouped by
the county code the card prints (``Jud.CJ``) and typed the way the card does: ``M`` for a
municipality (``Mun.``), ``O`` for a town (``Oraș``), ``C`` for a commune (``Com.``) and ``S``
for a locality of a commune (``Sat``).

    pip download django-siruta==0.3.0 --no-deps -d /tmp/siruta
    python tools/build_localities.py /tmp/siruta/django_siruta-0.3.0-py3-none-any.whl
"""

from __future__ import annotations

import ast
import re
import sys
import unicodedata
import zipfile
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "src" / "docfill" / "data" / "ro_localities.txt"
_CEDILLA = str.maketrans("ŞşŢţ", "ȘșȚț")
# Words written in lower case inside a name: "Valea lui Mihai", "Băița de sub Codru".
_SMALL = {"de", "din", "lui", "la", "sub", "pe", "cu", "cel", "în", "al"}
_ROMAN = {"i", "ii", "iii", "iv"}  # "Gersa II"; not "vii" (vineyards: "Apele Vii")

